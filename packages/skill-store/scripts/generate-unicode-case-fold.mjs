import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';

const unicodeVersion = '17.0.0';
const sourceUrl = `https://www.unicode.org/Public/${unicodeVersion}/ucd/CaseFolding.txt`;
const outputUrl = new URL('../src/unicode-case-fold-data.ts', import.meta.url);
const expectedSourceSha256 = 'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183';
const expectedEntryCount = 1585;

const response = await fetch(sourceUrl);
if (!response.ok) {
  throw new Error(`failed to download ${sourceUrl}: HTTP ${response.status}`);
}
const sourceBytes = Buffer.from(await response.arrayBuffer());
const sourceSha256 = createHash('sha256').update(sourceBytes).digest('hex');
if (sourceSha256 !== expectedSourceSha256) {
  throw new Error(
    `unexpected CaseFolding.txt SHA-256: expected ${expectedSourceSha256}, got ${sourceSha256}`,
  );
}

const entries = [];
for (const rawLine of sourceBytes.toString('utf8').split(/\r?\n/)) {
  const line = rawLine.split('#', 1)[0]?.trim();
  if (!line) continue;
  const [source, status, mapping] = line.split(';').map((part) => part.trim());
  if ((status !== 'C' && status !== 'F') || !source || !mapping) continue;
  const folded = mapping
    .split(/\s+/)
    .map((value) => String.fromCodePoint(Number.parseInt(value, 16)))
    .join('');
  entries.push(`  [0x${source.toLowerCase()}, ${JSON.stringify(folded)}],`);
}
if (entries.length !== expectedEntryCount) {
  throw new Error(
    `unexpected full case-fold entry count: expected ${expectedEntryCount}, got ${entries.length}`,
  );
}

const output = `// Generated by scripts/generate-unicode-case-fold.mjs from:
// ${sourceUrl}
// Source SHA-256: ${sourceSha256}
// Unicode data terms: https://www.unicode.org/terms_of_use.html
// Do not edit by hand.

export const FULL_UNICODE_CASE_FOLD = new Map<number, string>([
${entries.join('\n')}
]);
`;

await writeFile(outputUrl, output, 'utf8');
