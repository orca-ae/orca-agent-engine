// Local Linux-kernel acceptance. Build packages first, then run this with Docker.
import { execFileSync, spawnSync } from 'node:child_process';
import { copyFileSync, cpSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  ENVIRONMENT_PACKAGES_ROOT,
  buildEnvironmentPackagesProbe,
  buildStageEnvironmentPackagesCommand,
  buildEnvironmentPackageMountTargets,
  buildEnvironmentPackageBoundaryProbe,
  buildSandboxWritePolicy,
  buildBubblewrapCommand,
  normalizeEnvironmentPackages,
  buildOpenSandboxExecdAuthenticationProbeCommand,
} from '../packages/sandbox-runtime/dist/index.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const execdBinary = process.argv[2];
if (!execdBinary)
  throw new Error(
    'usage: node scripts/test-environment-packages-docker.mjs <pinned-linux-execd-binary>',
  );
const directory = mkdtempSync(join(tmpdir(), 'orca-package-acceptance-'));
const id = `${process.pid}-${Date.now()}`;
const image = `orca-environment-packages-test:${id}`;
const volume = `orca-environment-packages-test-${id}`;
const invalidVolume = `${volume}-invalid`;
function docker(args) {
  execFileSync('docker', args, { stdio: 'inherit', timeout: 1_200_000 });
}
function quote(value) {
  return `'${value.replace(/'/g, `'"'"'`)}'`;
}

try {
  copyFileSync(execdBinary, join(directory, 'execd'));
  copyFileSync(
    join(root, 'services/harness-server/sandbox-templates/orca-default/orca-environment-probe.c'),
    join(directory, 'probe.c'),
  );
  cpSync(
    join(root, 'services/harness-server/test/fixtures/environment-packages/malicious'),
    join(directory, 'malicious'),
    { recursive: true },
  );
  cpSync(
    join(root, 'services/harness-server/test/fixtures/environment-packages/invalid-rootfs'),
    join(directory, 'invalid-rootfs'),
    { recursive: true },
  );
  writeFileSync(
    join(directory, 'Dockerfile'),
    `
FROM node:22-trixie-slim@sha256:517aa41d78545cb1b8c67b13655b4c13ede1ee9df1da8aab54cd7434aefbcaf8
RUN apt-get update && apt-get install -y --no-install-recommends bubblewrap socat ripgrep gcc libc6-dev ca-certificates && rm -rf /var/lib/apt/lists/*
COPY probe.c /tmp/probe.c
RUN mkdir -p /usr/local/libexec && cc -Os -static -Wall -Werror /tmp/probe.c -o /usr/local/libexec/orca-environment-probe
COPY execd /usr/local/libexec/orca-test-execd
COPY malicious /opt/orca-package-fixtures/malicious
COPY invalid-rootfs /opt/orca-package-fixtures/invalid-rootfs
`,
  );
  docker(['build', '-t', image, directory]);
  docker(['volume', 'create', volume]);

  const packages = normalizeEnvironmentPackages({
    apt: ['jq'],
    pip: ['idna==3.10'],
    npm: ['is-number@7.0.0', 'file:/opt/orca-package-fixtures/malicious'],
    cargo: ['ripgrep@14.1.1'],
    gem: ['rake:13.2.1'],
    go: ['github.com/rakyll/hey@v0.1.4'],
  });
  // Exercise the exact command generated by the provider, without importing its server.
  const python = `import ast, hashlib, json, shlex, sys
tree=ast.parse(open(sys.argv[1]).read())
nodes=[node for node in tree.body if (isinstance(node,ast.FunctionDef) and node.name=='_package_init_container') or (isinstance(node,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='_PACKAGES_ROOT' for t in node.targets))]
exec(compile(ast.Module(body=nodes,type_ignores=[]),'provider','exec'))
print(json.dumps(_package_init_container('fixture',json.loads(sys.argv[2]),{})['command']))`;
  const installCommand = (requested) =>
    JSON.parse(
      execFileSync(
        'python3',
        [
          '-c',
          python,
          join(root, 'charts/opensandbox-patches/files/batchsandbox_provider.py'),
          JSON.stringify(requested),
        ],
        { encoding: 'utf8' },
      ),
    );
  docker([
    'run',
    '--rm',
    '--cap-drop=NET_RAW',
    '--cap-drop=MKNOD',
    '-v',
    `${volume}:${ENVIRONMENT_PACKAGES_ROOT}`,
    image,
    ...installCommand(packages),
  ]);

  const policy = buildSandboxWritePolicy([], {
    includeSkillsRoot: true,
    environmentPackages: true,
  });
  const roots = [...policy.readonlyPaths, ...policy.writablePaths.map((entry) => entry.path)];
  const drop =
    'setpriv --reuid 1000 --regid 1000 --clear-groups --bounding-set=-all --no-new-privs -- ';
  const workload = [
    'test -z "${EXECD_ACCESS_TOKEN:-}"',
    "node -e \"if(require('fs').readFileSync('/proc/1/environ','utf8').includes('EXECD_ACCESS_TOKEN='))process.exit(1)\"",
    'node -e "fetch(\'http://127.0.0.1:44772/ping\').then(r => { if (r.status !== 401) process.exit(1); })"',
    'test "$(cat /workspace/skills/SKILL.md)" = pinned',
    'test "$(id)" = poisoned-id',
    'jq -n -e true',
    'python -c "import idna; assert idna.__version__ == \'3.10\'"',
    'node -e "if(!require(\'is-number\')(42))process.exit(1)"',
    'rg --version',
    "ruby -e \"require 'rake'; abort unless Rake::VERSION == '13.2.1'\"",
    'hey -h >/dev/null 2>&1 || test "$?" = 2',
    'printf verified > /mnt/session/outputs/result',
    '! (printf denied >> /workspace/skills/SKILL.md)',
    '! (printf denied > /etc/orca-package-escape)',
  ].join('\n');
  const worker = `
import fs from 'node:fs';
import { LocalSandboxRuntime, createManagedToolSandboxManager, buildSandboxWritePolicy } from '/work/packages/sandbox-runtime/dist/index.js';
const runtime = new LocalSandboxRuntime({ harnessWorkDir: '/tmp/orca-package-worker', allowedNetworkHosts: [], networkUnrestricted: true, managedToolFilesystem: true, useEnvironmentPackages: true, manager: createManagedToolSandboxManager() });
const raw = await runtime.acquire({});
try {
  const policy = buildSandboxWritePolicy([], { includeSkillsRoot: true, environmentPackages: true, networkUnrestricted: true });
  await raw.prepareFilesystemRoots(['/workspace/skills', '/mnt/session/outputs']);
  const root = raw.rootDir();
  fs.mkdirSync(root + '/workspace/skills', { recursive: true });
  fs.mkdirSync(root + '/mnt/session/outputs', { recursive: true });
  fs.writeFileSync(root + '/workspace/skills/SKILL.md', 'pinned');
  await raw.prepareWritePolicy(policy);
  const result = await raw.runWithWritePolicy({ tool: 'bash', args: { command: ${JSON.stringify('set -eu\n' + workload)} } }, policy);
  if (result.exit_code !== 0) throw new Error('worker package execution failed: ' + result.stderr);
  if (fs.readFileSync(root + '/mnt/session/outputs/result', 'utf8') !== 'verified') throw new Error('worker output missing');
} finally { await raw.destroy(); }
console.log('Managed worker package execution verified');`;
  const runtime = [
    'set -eu',
    '/usr/local/libexec/orca-test-execd > /tmp/orca-test-execd.log 2>&1 &',
    `node -e ${quote("(async () => { for(let i=0; i<100; i++) { try { const r=await fetch('http://127.0.0.1:44772/ping', {headers:{'X-EXECD-ACCESS-TOKEN':process.env.EXECD_ACCESS_TOKEN}}); if(r.ok)return; } catch {} await new Promise(resolve=>setTimeout(resolve,100)); } process.exit(1); })()")}`,
    buildOpenSandboxExecdAuthenticationProbeCommand(),
    'test "$(id -u)" = 0',
    'mkdir -p /mnt/session/outputs /workspace/skills',
    'chown 1000:1000 /mnt/session/outputs',
    'printf pinned > /workspace/skills/SKILL.md',
    buildEnvironmentPackagesProbe(packages),
    buildStageEnvironmentPackagesCommand(),
    buildEnvironmentPackageMountTargets(roots),
    drop + buildEnvironmentPackageBoundaryProbe(policy),
    drop + buildBubblewrapCommand('set -eu\n' + workload, policy),
    `node --input-type=module -e ${quote(worker)}`,
    'test "$(cat /mnt/session/outputs/result)" = verified',
    `test "$(cat ${ENVIRONMENT_PACKAGES_ROOT}/init-saw-token)" = absent`,
    'sleep 2',
    `test ! -e ${ENVIRONMENT_PACKAGES_ROOT}/late-write`,
    'test "$(id -u)" = 0',
    'printf "Six managers and isolated package execution verified\\n"',
  ].join('\n');
  // Docker masks parts of /proc by default; fresh nested proc mounts need this
  // local-test option. Production gVisor keeps its existing no-procMount policy.
  docker([
    'run',
    '--rm',
    '--cap-add=SYS_ADMIN',
    '--cap-add=SETFCAP',
    '--security-opt=seccomp=unconfined',
    '--security-opt=apparmor=unconfined',
    '--security-opt=systempaths=unconfined',
    '-e',
    'ORCA_TEST_RUNTIME_TOKEN=runtime-only-fixture',
    '-e',
    'EXECD_ACCESS_TOKEN=eeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee',
    '-v',
    `${volume}:${ENVIRONMENT_PACKAGES_ROOT}:ro`,
    '-v',
    `${root}:/work:ro`,
    image,
    '/bin/bash',
    '-c',
    runtime,
  ]);
  const invalidPackages = { npm: ['file:/opt/orca-package-fixtures/invalid-rootfs'] };
  docker(['volume', 'create', invalidVolume]);
  docker([
    'run',
    '--rm',
    '-v',
    `${invalidVolume}:${ENVIRONMENT_PACKAGES_ROOT}`,
    image,
    ...installCommand(invalidPackages),
  ]);
  const rejection = spawnSync(
    'docker',
    [
      'run',
      '--rm',
      '-v',
      `${invalidVolume}:${ENVIRONMENT_PACKAGES_ROOT}:ro`,
      image,
      '/bin/bash',
      '-c',
      buildEnvironmentPackagesProbe(invalidPackages),
    ],
    { encoding: 'utf8', timeout: 60_000 },
  );
  if (rejection.status !== 1 || !rejection.stderr.includes('invalid environment package rootfs'))
    throw new Error('aliased package root was not rejected');
  console.log('Aliased installer root rejected before tool execution');
} finally {
  try {
    docker(['volume', 'rm', invalidVolume]);
  } catch {
    /* Created only by the negative fixture. */
  }
  try {
    docker(['volume', 'rm', volume]);
  } catch {
    /* No volume exists when image setup fails. */
  }
  try {
    docker(['image', 'rm', image]);
  } catch {
    /* Keep unrelated Docker resources intact. */
  }
  rmSync(directory, { recursive: true, force: true });
}
