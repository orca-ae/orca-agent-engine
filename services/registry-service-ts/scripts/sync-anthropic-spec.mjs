/**
 * Vendor Anthropic's published OpenAPI spec into `vendor/anthropic/`.
 *
 * Run with `pnpm anthropic:sync`. Writes two files:
 *
 *   vendor/anthropic/openapi.json  — the downloaded bytes, verbatim
 *   vendor/anthropic/PINNED.json   — provenance: source URL and our own sha256
 *
 * The spec URL is discovered from `.stats.yml` in `anthropic-sdk-typescript`.
 * That file is the only machine-readable pointer Anthropic publishes to the
 * current spec artifact. **Reading it is URL discovery and nothing more** — it
 * is not an adoption of that SDK version, and no consumer of the vendored spec
 * may treat the TypeScript SDK as defining the API surface. The spec does.
 *
 * `.stats.yml` also carries an `openapi_spec_hash`. It is deliberately *not*
 * used as a checksum: it is not a digest of the served bytes. The Python SDK
 * pins a different spec URL under the same `openapi_spec_hash`, and both URLs
 * serve byte-identical content — so the value cannot be a hash of either. We
 * compute our own sha256 over the downloaded bytes and pin that, labelled as
 * locally computed so nobody later mistakes it for an upstream-published digest.
 *
 * `PINNED.json` carries no fetch timestamp on purpose. A timestamp would dirty
 * the tree on every run, which would make the `git diff --exit-code` drift gate
 * in CI fire on a no-op sync. Running this twice with no upstream change is a
 * byte-identical no-op.
 */
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';

const STATS_URL =
  'https://raw.githubusercontent.com/anthropics/anthropic-sdk-typescript/main/.stats.yml';

const vendorDir = new URL('../vendor/anthropic/', import.meta.url);
const specUrl = new URL('openapi.json', vendorDir);
const pinnedUrl = new URL('PINNED.json', vendorDir);

async function fetchOrThrow(url, what) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`failed to download ${what} from ${url}: HTTP ${response.status}`);
  }
  return Buffer.from(await response.arrayBuffer());
}

/**
 * Pull `openapi_spec_url` out of `.stats.yml`. Hand-parsed rather than run
 * through a YAML library: the file is four flat `key: value` lines, and a
 * dependency-free reader fails loudly if that ever stops being true.
 */
function readSpecUrlFromStats(statsText) {
  const line = statsText
    .split('\n')
    .map((entry) => entry.trim())
    .find((entry) => entry.startsWith('openapi_spec_url:'));
  if (!line) {
    throw new Error(`no \`openapi_spec_url\` key in ${STATS_URL}; the file's shape changed`);
  }
  const value = line.slice('openapi_spec_url:'.length).trim();
  if (!value.startsWith('https://')) {
    throw new Error(`\`openapi_spec_url\` in ${STATS_URL} is not an https URL: ${value}`);
  }
  return value;
}

const statsText = (await fetchOrThrow(STATS_URL, 'Anthropic SDK .stats.yml')).toString('utf8');
const sourceUrl = readSpecUrlFromStats(statsText);

const specBytes = await fetchOrThrow(sourceUrl, 'Anthropic OpenAPI spec');
const sha256 = createHash('sha256').update(specBytes).digest('hex');

// The URL ends in `.yml` but the artifact has been JSON for as long as we have
// vendored it. Parse before writing so a format change fails here rather than
// silently poisoning the differ with an unparseable file.
let spec;
try {
  spec = JSON.parse(specBytes.toString('utf8'));
} catch (cause) {
  throw new Error(
    `${sourceUrl} is not JSON despite the .yml extension; the upstream format changed`,
    { cause },
  );
}
if (typeof spec.openapi !== 'string' || !spec.paths || typeof spec.paths !== 'object') {
  throw new Error(`${sourceUrl} does not look like an OpenAPI document (no openapi/paths keys)`);
}

const pinned = {
  _comment:
    'Generated by scripts/sync-anthropic-spec.mjs. Do not edit by hand; run `pnpm anthropic:sync`.',
  source_url: sourceUrl,
  discovered_from: STATS_URL,
  // Named for what it is. `.stats.yml`'s `openapi_spec_hash` is NOT a digest of
  // these bytes and must never be substituted here.
  sha256_of_openapi_json_computed_locally: sha256,
  openapi_version: spec.openapi,
  path_count: Object.keys(spec.paths).length,
  byte_count: specBytes.byteLength,
};

await mkdir(vendorDir, { recursive: true });
// Write the downloaded bytes verbatim — no re-serialization. The pinned sha256
// must stay a digest of a file we can hand to anyone as "what Anthropic serves".
await writeFile(specUrl, specBytes);
await writeFile(pinnedUrl, `${JSON.stringify(pinned, null, 2)}\n`, 'utf8');

process.stdout.write(
  [
    `anthropic spec synced from ${sourceUrl}`,
    `  sha256 (locally computed): ${sha256}`,
    `  openapi ${spec.openapi}, ${pinned.path_count} paths, ${pinned.byte_count} bytes`,
    '',
  ].join('\n'),
);
