/** Generate the standalone admin contract without altering public conformance. */
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import SwaggerParser from '@apidevtools/swagger-parser';
import { dump } from 'js-yaml';
import { buildObservabilityOpenApiDocument } from '../src/contracts/observability-openapi-schema.js';

// Do not embed HEAD or a timestamp: unrelated commits must not cause spec drift.
const { version } = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
const files = ['agent-observability.contract.ts', 'platform-agent-observability.contract.ts'];
const hashes = Object.fromEntries(
  await Promise.all(
    files.map(async (name) => [
      name,
      createHash('sha256')
        .update(await readFile(new URL('../src/contracts/' + name, import.meta.url)))
        .digest('hex'),
    ]),
  ),
);
const document = buildObservabilityOpenApiDocument({ version });
document['x-orca-source'] = { repository: 'orca-ae/orca-agent-engine', contracts: hashes };
await SwaggerParser.validate(structuredClone(document));
await writeFile(
  new URL('../openapi/observability-admin.yaml', import.meta.url),
  '# Generated by pnpm openapi:observability:gen. Do not edit by hand.\n' +
    dump(document, { lineWidth: 100, noRefs: true }),
);
console.log('wrote openapi/observability-admin.yaml (admin listener only)');
